inline Panel* self(esp_lcd_panel_t* p){return reinterpret_cast<Panel*>(p);} 
int command(const Panel* p,int cmd,bool color=false){
 if(p->cfg.bus!=board::BusKind::qspi) return cmd;
 return ((color?0x32:0x02)<<24)|(cmd<<8);
}
esp_err_t tx(Panel* p,int cmd,const void* data,size_t n){return esp_lcd_panel_io_tx_param(p->io,command(p,cmd),data,n);} 
esp_err_t del(esp_lcd_panel_t* base){auto* p=self(base); if(board::valid_pin(p->cfg.pins.reset)) gpio_reset_pin(static_cast<gpio_num_t>(p->cfg.pins.reset)); std::free(p); return ESP_OK;}
esp_err_t reset(esp_lcd_panel_t* base){auto* p=self(base); if(board::valid_pin(p->cfg.pins.reset)){gpio_set_level(static_cast<gpio_num_t>(p->cfg.pins.reset),0);vTaskDelay(pdMS_TO_TICKS(10));gpio_set_level(static_cast<gpio_num_t>(p->cfg.pins.reset),1);vTaskDelay(pdMS_TO_TICKS(120));}else{tx(p,SWRESET,nullptr,0);vTaskDelay(pdMS_TO_TICKS(120));}return ESP_OK;}
void common_init(Panel* p){const std::uint8_t format=0x55;tx(p,COLMOD,&format,1);const std::uint8_t mad= p->cfg.color_order==board::ColorOrder::bgr?0x08:0x00;tx(p,MADCTL,&mad,1);}
