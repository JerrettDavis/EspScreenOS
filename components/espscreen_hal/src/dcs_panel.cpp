 if(p->cfg.driver==board::DisplayDriver::st77922){for(const auto& entry:es3c35p_init){ESP_RETURN_ON_ERROR(tx(p,entry.command,entry.length?entry.data.data():nullptr,entry.length),TAG,"ES3C35P init");if(entry.delay_ms)vTaskDelay(pdMS_TO_TICKS(entry.delay_ms));}return ESP_OK;}
 tx(p,SLPOUT,nullptr,0);vTaskDelay(pdMS_TO_TICKS(120));
