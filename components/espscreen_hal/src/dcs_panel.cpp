esp_err_t draw(esp_lcd_panel_t* base,int xs,int ys,int xe,int ye,const void* colors){auto* p=self(base);xs+=p->x_gap;xe+=p->x_gap;ys+=p->y_gap;ye+=p->y_gap;
 std::uint8_t col[]={static_cast<std::uint8_t>(xs>>8),static_cast<std::uint8_t>(xs),static_cast<std::uint8_t>((xe-1)>>8),static_cast<std::uint8_t>(xe-1)};
 std::uint8_t row[]={static_cast<std::uint8_t>(ys>>8),static_cast<std::uint8_t>(ys),static_cast<std::uint8_t>((ye-1)>>8),static_cast<std::uint8_t>(ye-1)};
 ESP_RETURN_ON_ERROR(tx(p,CASET,col,4),TAG,"column");ESP_RETURN_ON_ERROR(tx(p,RASET,row,4),TAG,"row");
 return esp_lcd_panel_io_tx_color(p->io,command(p,RAMWR,true),colors,(xe-xs)*(ye-ys)*2);
}
