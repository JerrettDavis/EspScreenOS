esp_err_t swap_xy(esp_lcd_panel_t* base,bool swap){auto* p=self(base);p->swap=swap;return mirror(base,p->mx,p->my);} 
esp_err_t onoff(esp_lcd_panel_t* base,bool on){auto* p=self(base);return tx(p,on?DISPON:DISPOFF,nullptr,0);} 
